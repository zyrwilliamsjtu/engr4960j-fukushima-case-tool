/* Run with Node; no packages required. Tests the replaceable preview adapter. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../../..');
const store = new Map();
const context = { window: {}, localStorage: { getItem: k => store.get(k) || null, setItem: (k,v) => store.set(k,v) }, setTimeout, clearTimeout, Date };
vm.createContext(context);
for (const file of ['src/data/fukushima.js', 'src/data/mock-state.js', 'src/ui/preview-runtime.js']) vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),context);
const data = context.window.CASE_DATA;
const make = options => context.window.FrontendPreviewRuntime.create(data,options || { persistent:false });
const send = (engine,type,payload) => engine.dispatch({type,payload});
const add = (engine,type,step,fields) => {send(engine,'ADD_ITEM',{type,step,fields});return Object.values(engine.getState().items).at(-1).id;};
const engine = make();
assert.equal(Object.keys(engine.getState().items).length,0);
const question = add(engine,'Q',1,{text:'Should the team disclose an uncertainty?',actors:['Test actor'],isCore:true});
const gap = add(engine,'M',3,{text:'What information was available?'});
send(engine,'LINK',{from:gap,to:question,kind:'fact-supports-question',why:'The timing may affect responsibility.'});
const assumption = add(engine,'A',4,{text:'A tentative test assumption.'});
send(engine,'SET_BASIS',{id:assumption,refs:[gap],gap,why:'A stated, provisional inference.'});
send(engine,'ANSWER',{question});
const answer = Object.values(engine.getState().items).find(x=>x.type==='R');
assert.equal(answer.text,'','Answers start blank; no generated conclusion.');
send(engine,'UPDATE_ITEM',{id:answer.id,fields:{text:'Our independently written test judgment.',reason:'Our independently written justification.'}});
send(engine,'SET_STATUS',{step:4,status:'checked'});
send(engine,'SET_STATUS',{step:8,status:'checked'});
send(engine,'UPDATE_ITEM',{id:gap,fields:{text:'A revised information gap.'}});
assert.equal(engine.getState().stepStatus[4],'stale');
assert.equal(engine.getState().stepStatus[8],'stale');
assert.equal(engine.getState().items[answer.id].text,'Our independently written test judgment.');
assert.equal(engine.getState().items[assumption].text,'A tentative test assumption.');
engine.createSnapshot('reviewed');
engine.createSnapshot('initial');
assert.deepEqual(Array.from(engine.getState().snapshots,x=>x.id),['SN-01','SN-02'],'Both slots survive saving in reverse order.');
send(engine,'UPDATE_ITEM',{id:question,fields:{text:'Changed question?'}});
assert.notEqual(engine.getState().snapshots[0].payload.items[question].text,'Changed question?');
engine.restoreSnapshot('SN-01');
assert.equal(engine.getState().items[question].text,'Should the team disclose an uncertainty?');
const exported = engine.exportProject(), before = JSON.stringify(engine.getState());
for (const corrupt of [ 'invalid JSON', Object.assign(JSON.parse(exported),{caseId:'other'}), Object.assign(JSON.parse(exported),{stateVersion:'1.0'}), (()=>{const s=JSON.parse(exported);s.items[question].actors='broken';return s;})(), (()=>{const s=JSON.parse(exported);s.relations[0].to='missing';return s;})() ]) {
  assert.equal(engine.importProject(corrupt).ok,false);
  assert.equal(JSON.stringify(engine.getState()),before,'Bad imports are atomic.');
}
assert.equal(make().importProject(exported).ok,true);
assert.equal(make().importProject(context.window.MOCK_USER_STATE).ok,true,'Repository mock remains compatible.');
const pa=add(engine,'PA',6,{principleId:data.principles[0].id,text:'Test application reason.'});
send(engine,'UPDATE_ITEM',{id:pa,fields:{appliesTo:[question]}});
assert.ok(engine.getState().relations.some(r=>r.from===pa&&r.to===question&&r.kind==='principle-applies-to'));
send(engine,'DELETE_ITEM',{id:gap});
assert.ok(!engine.getState().relations.some(r=>r.from===gap||r.to===gap));
assert.equal(engine.getState().items[assumption].basisRefs.length,0);
assert.equal(engine.getState().items[answer.id].text,'Our independently written test judgment.');
const nextGap=add(engine,'M',3,{});assert.notEqual(nextGap,gap,'Deleted identifiers are not recycled.');
const persist=make({persistent:true});add(persist,'Q',1,{text:'Persisted test?'});persist.flush();
assert.ok(make({persistent:true}).exportProject().includes('Persisted test?'));
store.set('engr4960j.frontend.preview.v2','{"stateVersion":"old"}');
const incompatible=make({persistent:true});add(incompatible,'Q',1,{text:'New working record?'});incompatible.flush();
assert.equal(store.get('engr4960j.frontend.preview.v2'),'{"stateVersion":"old"}','Unsupported data is retained.');
assert.equal(incompatible.getSaveStatus(),'memory');
assert.ok(incompatible.recoveryData());
assert.equal(engine.validateStep(10).errors.length,0,'Quantity suggestions never lock navigation.');
engine.flush();
console.log('PASS: empty answers, reference graph, stale propagation, immutable snapshots, atomic import, mock compatibility, storage recovery, nonblocking checks.');
